// Function to expand search terms with related keywords
export const expandSearchTerm = (searchTerm: string): string[] => {
  const lowerTerm = searchTerm.toLowerCase().trim();
  const expansions = new Set([lowerTerm]);
  
  // Check enhanced keywords
  for (const [key, keywords] of Object.entries(ENHANCED_SEARCH_KEYWORDS)) {
    if (lowerTerm.includes(key) || keywords.some(k => lowerTerm.includes(k))) {
      keywords.forEach(k => expansions.add(k));
      expansions.add(key);
    }
  }
  
  // Check abbreviations
  for (const [abbr, expansionList] of Object.entries(TOOL_ABBREVIATIONS)) {
    if (lowerTerm.includes(abbr) || expansionList.some(e => lowerTerm.includes(e))) {
      expansionList.forEach(e => expansions.add(e));
      expansions.add(abbr);
    }
  }
  
  // Check brand mappings
  for (const [brand, associations] of Object.entries(BRAND_MAPPINGS)) {
    if (lowerTerm.includes(brand) || associations.some(a => lowerTerm.includes(a))) {
      associations.forEach(a => expansions.add(a));
      expansions.add(brand);
    }
  }
  
  // Check emotional keywords
  for (const [emotion, synonyms] of Object.entries(EMOTIONAL_KEYWORDS)) {
    if (lowerTerm.includes(emotion) || synonyms.some(s => lowerTerm.includes(s))) {
      synonyms.forEach(s => expansions.add(s));
      expansions.add(emotion);
    }
  }
  
  return Array.from(expansions);
};